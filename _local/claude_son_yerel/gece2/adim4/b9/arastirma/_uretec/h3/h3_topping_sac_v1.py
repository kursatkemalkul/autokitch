def _kesen(bolge, sekiller, pay=0.5):
    bb = bolge.BoundingBox(); out = []
    for s in sekiller:
        b = s.BoundingBox()
        if b.xmin < bb.xmax + pay and bb.xmin < b.xmax + pay and b.ymin < bb.ymax + pay and bb.ymin < b.ymax + pay and b.zmin < bb.zmax + pay and bb.zmin < b.zmax + pay:
            out.append(s)
    return out


def _pu(bolge, kesenler):
    k = _kesen(bolge, kesenler)
    if not k: return bolge
    sh = bolge.cut(cq.Compound.makeCompound(k))
    return sh.clean() if hasattr(sh, "clean") else sh


