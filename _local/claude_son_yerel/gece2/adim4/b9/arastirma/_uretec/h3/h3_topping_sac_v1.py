def tapa_d(g, profil, uc="ust", t=2.0, pah=2.5, ad=None):
    """dikdörtgen boru ucuna tapa (köşeler pah, çevresi TIG alın — taşlanır) · eksen y"""
    assert profil.eksen == "y"
    bx, bz = profil.bo["x"], profil.bo["z"]
    C = profil.merkez(profil.a1 if uc == "ust" else profil.a0)
    s = g.sac(ad or profil.ad + "_tapa", "braket", t=t)
    u0, u1, v0, v1 = C[0] - bx / 2, C[0] + bx / 2, -(C[2] + bz / 2), -(C[2] - bz / 2)
    c = pah
    y0 = profil.a1 if uc == "ust" else profil.a0 - t
    s.taban([(u0 + c, v0), (u1 - c, v0), (u1, v0 + c), (u1, v1 - c), (u1 - c, v1), (u0 + c, v1), (u0, v1 - c), (u0, v0 + c)],
            O=(0, y0, 0), ex=(1, 0, 0), ey=(0, 0, -1), ad="tapa")
    return s


