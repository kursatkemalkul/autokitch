    yan_boy = (IY[1] + t) - IY[0]                                       # 989,2 → yan kenarlar raf üstünde (1152)
    sag = P.flans(1, yan_boy, yon=+1, ad="sag_yan")
    on = P.flans(2, 12.0, yon=-1, ad="on_donus")                        # yukarı (dışa)
