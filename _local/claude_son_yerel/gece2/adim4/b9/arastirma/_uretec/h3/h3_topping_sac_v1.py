def _uv(P, ex, ey):
    P = np.asarray(P, float)
    return float(np.dot(P, ex)), float(np.dot(P, ey))


def taban(s, ad, d0, ex, ey, rect=None, poly=None):
    """eksene paralel düzlem: n = ex × ey · alt yüz (z = 0) n ekseninde d0'da · rect (u0, u1, v0, v1) ya da poly (CCW, u-v)"""
    ex, ey = np.asarray(ex, float), np.asarray(ey, float); n = np.cross(ex, ey)
    O = np.abs(n) * d0
    if poly is None:
        u0, u1, v0, v1 = rect
        poly = [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]
    return s.taban(poly, O=tuple(O), ex=tuple(ex), ey=tuple(ey), ad=ad)


def tel_delik(P, ad_eski, tip="eski_aciklik", filtre=None, kirp=None, parca=""):
    """eski parçanın iç tellerini (dünya) P paneline (u, v) kesik olarak aktarır · filtre(bb) → True olanlar · kirp: (umin, umax, vmin, vmax)"""
    out = []
    for w in _delik_yukle().get(ad_eski, []):
        uv = [tuple(P.yerel(np.asarray(p, float))[:2]) for p in w]
        us = [a for a, b in uv]; vs = [b for a, b in uv]
        bb = (min(us), max(us), min(vs), max(vs))
        if filtre is not None and not filtre(bb): continue
        if len(uv) >= 12:                                                  # daire mi? (örneklenmiş kenar · merkezden eşit uzak)
            cu, cv = sum(us) / len(us), sum(vs) / len(vs)
            rr = [math.hypot(a - cu, b - cv) for a, b in uv]
            if max(rr) - min(rr) < 0.05 and (kirp is None or (kirp[0] <= cu - rr[0] and cu + rr[0] <= kirp[1] and kirp[2] <= cv - rr[0] and cv + rr[0] <= kirp[3])):
                out.append(P.delik(cu, cv, 2.0 * sum(rr) / len(rr), tip=tip, parca=parca or ("eski %s deliği (birebir)" % ad_eski)))
                continue
        if kirp is not None:
            uv = [(min(max(a, kirp[0]), kirp[1]), min(max(b, kirp[2]), kirp[3])) for a, b in uv]
        # tekrar eden ardışık noktaları ayıkla
        q = []
        for p in uv:
            if not q or abs(p[0] - q[-1][0]) > 1e-6 or abs(p[1] - q[-1][1]) > 1e-6: q.append(p)
        if len(q) > 2 and abs(q[0][0] - q[-1][0]) < 1e-6 and abs(q[0][1] - q[-1][1]) < 1e-6: q.pop()
        if len(q) < 3: continue
        if S._alan2(q) < 0: q = q[::-1]
        out.append(P.kesik(q, tip=tip, parca=parca or ("eski %s açıklığı (birebir)" % ad_eski)))
    return out


