def uygula_tc(L):
    """TC.PARCALAR: eski gövde (+ v3.7 kanat kabukları) çıkar, yeni TC gövdesi girer · her TC.modul() sonrası çağrılır (idempotent)"""
    if any(p["ad"] == ISARET_TC for p in L): return L
    var = set(p["ad"] for p in L)
    eksik = [a for a in ESKI_TC if a not in var]
    assert not eksik, ("TOPPING_SAC: eski TC gövde parçası yok", eksik)
    dus = set(ESKI_TC) | set(ESKI_TC_KABUK)
    L[:] = [p for p in L if p["ad"] not in dus]
    yeni = _G.setdefault("TC", parcalar_tc())
    cak = set(p["ad"] for p in L) & set(q["ad"] for q in yeni)
    assert not cak, ("TOPPING_SAC: TC mekanizmasıyla ad çakışması", sorted(cak)[:8])
    L.extend(dict(q) for q in yeni)
    return L


def uygula_tu(TU, rapor=None):
    """TU.P: eski soğuk oda / kapak parçaları çıkar, yenileri girer (TU çerçevesi) · idempotent"""
