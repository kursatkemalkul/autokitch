# ================================================================ 6 · KOMŞU / KAİDE BAĞLANTILARI (M8) ================================================================
def m8_arka(g, etiket, taraf, y, karsi, karsi_kod):
    """kendinden taşıyıcı kabukta arka M8: yan sacın iç yüzüne punta 3 mm takviye lamı + PEM SP-M8 · yan sacta Ø9 · cıvata komşudan (ARAYÜZ)"""
    P = g.PANEL[taraf]["yan"]; z = Z_M8_ARKA
    s = g.sac("govde_m8_%s_lama" % etiket, "braket")
    if taraf == "sol":
        Q = taban(s, "lama", XI0, (0, 1, 0), (0, 0, 1), rect=(y - 15.0, y + 15.0, z - 10.5, z + 10.5)); xs, sx = XI0 + 3.0, 1.0; uvq = (y, z); uvp = (y, z)
    else:
        Q = taban(s, "lama", XI1, (0, 1, 0), (0, 0, -1), rect=(y - 15.0, y + 15.0, -(z + 10.5), -(z - 10.5))); xs, sx = XI1 - 3.0, -1.0; uvq = (y, -z); uvp = (y, -z)
    s.punta(P.sac, [(xs - sx * 3.0, y + dy, z + dz) for dy in (-10.0, 10.0) for dz in (-6.5, 6.5)], not_="takviye lamı → yan sac (panel montajından önce)")
    ps, c, ms = S.pem_somun("SP", "M8", (xs, y, z), (sx, 0, 0), s.t, ad="govde_m8_%s" % etiket, birim=g.birim)
    Q.delik(uvq[0], uvq[1], c["delik"], tip="pem_somun", parca=ps["meta"]["parca"], pem_tip="SP", kenar_min=c["kenar"], min_sac=ms)
    g.eleman(ps)
    gecis = S.STD.delik_iso273("M8")
    P.delik(uvp[0], uvp[1], gecis, tip="vida_deligi", parca="TOPPING↔%s M8 (ISO 273 orta)" % karsi_kod)
    xk = (X0 - 1.5) if taraf == "sol" else (X1 + 1.5)                    # komşu sacın iç yüzü
    hp = S.DIN125["M8"][2]
    Pk = np.array([xk - sx * hp, y, z])
    pu = S.pul("DIN125", "M8", tuple(Pk), (sx, 0, 0), ad="arayuz_m8_%s_pul" % etiket, birim=g.birim)
    vd = S.vida("ISO4762", "M8", 16, tuple(Pk), (sx, 0, 0), ad="arayuz_m8_%s" % etiket, birim=g.birim)
    g.arayuz(pu, karsi, "komşu sacta Ø%g delik (aynı eksen)" % gecis, "")
    g.arayuz(vd, karsi, "ISO 4762 M8 × 16 A2-70 + DIN 125 · komşu istasyonun içinden · TOPPING'de PEM SP-M8 (3 mm lamada)", "")
    kd = dict(etiket=etiket, karsi=karsi, karsi_kod=karsi_kod, cap=gecis, sac_t=1.5, eksen=[sx, 0.0, 0.0], merkez_dunya=[round(xk, 2), y, z], merkez_yerel=[round(xk, 2), y, z])
    g.KARSI_DELIK.append(kd)
    g.M8.append(dict(etiket=etiket, taraf=karsi_kod, yer="arka (yan sac + lama)", profil=None, a=y, ara_pul=0.0, dunya=[round(xk, 1), y, z], karsi_delik=kd))


