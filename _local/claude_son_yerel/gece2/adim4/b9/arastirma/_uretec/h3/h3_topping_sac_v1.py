BILINEN = {}                                                            # (gövde_ad, karşı_ad) → gerekçe  (denetimde izinli temas)


def arayuz_saplama(g, A, P, yon, dis, boy, ad, karsi_ad, karsi, gerek, sac_ad=None):
    """mekanizma / cihaz bağlantısı: A sacına PEM FHP saplama (gövde elemanı, baş A'nın yon'a ters yüzünde flush) + A'da delik ·
    pul + somun ARAYÜZ (mekanizma tarafında) · saplama mekanizma parçasındaki karşı delikten geçer → BILINEN"""
    yon = np.asarray(yon, float); yon = yon / np.linalg.norm(yon)
    uv = A.yerel(np.asarray(P, float))
    nA = A.normal(); tA = A.sac.t
    P0 = A.dunya(uv[0], uv[1], 0.0 if np.dot(yon, nA) > 0 else tA)
    sp, c = S.pem_saplama("FHP", dis, boy, tuple(P0), tuple(yon), ad=ad, birim=g.birim, sac_ad=sac_ad or A.sac.ad)
    A.delik(uv[0], uv[1], c["delik"], tip="pem_saplama", parca=sp["meta"]["parca"], pem_tip="FHP", kenar_min=c["kenar"], min_sac=c["min_sac"])
    sp["meta"]["arayuz_karsi"] = karsi_ad
    g.eleman(sp)
    pu = S.pul("DIN9021", dis, tuple(P0 + yon * (boy - S.ISO10511[dis][1] - S.DIN9021[dis][2] - 1.0)), tuple(yon), ad=ad + "_pul", birim=g.birim)
    g.arayuz(pu, karsi, gerek, "pul + ISO 10511 somun mekanizma tarafında")
    for k in (karsi_ad if isinstance(karsi_ad, (list, tuple)) else [karsi_ad]):
        BILINEN[(ad, k)] = "ARAYÜZ saplaması: %s parçasında karşı delik (%s) — mekanizma sahibine liste" % (k, gerek)
    return sp


# ================================================================ DİKDÖRTGEN PROFİL (GO.Profil kare; burada b_u × b_v) ================================================================
class ProfilD(GO.Profil):
    """304 dikdörtgen boru (EN 10219, dış R = 2t) · bo: {eksen: dış ölçü} iki dik eksen için (ör. y ekseni için {'x': 30, 'z': 20})"""
    def __init__(self, ad, eksen, a0, a1, c, bo, t=2.0, Ro=None, birim="GOVDE", kaynak=SURUM, not_=""):
        self.bo = dict(bo)
        super().__init__(ad, eksen, a0, a1, c, b=max(self.bo.values()), t=t, Ro=Ro, birim=birim, kaynak=kaynak, not_=not_)

    def _govde(self):
        dik = [k for k in "xyz" if k != self.eksen]
        bu, bv = self.bo[dik[0]], self.bo[dik[1]]
        dis = S.yuz_dikd_r(0.0, 0.0, bu, bv, 0.0, self.Ro)
        ic = S.yuz_dikd_r(0.0, 0.0, bu - 2 * self.t, bv - 2 * self.t, 0.0, self.Ro - self.t)
        sh = S._prizma(dis.cut(ic), self.a1 - self.a0)
        ex, ey, ez = GO.EKSEN[dik[0]], GO.EKSEN[dik[1]], GO.EKSEN[self.eksen]
        if np.linalg.det(np.column_stack([ex, ey, ez])) < 0: ey = -ey
        return S._tasi(sh, S._M(np.column_stack([ex, ey, ez]), self.merkez(self.a0)))

    def yari(self, yuz):
        return self.bo[yuz[1]] / 2.0

    def duvar_delik(self, yuz, a, kayma, cap, tip="delik", not_=""):
        n = GO._yuz_vektor(yuz)
        dik = [k for k in "xyz" if k not in (self.eksen, yuz[1])][0]
        p = self.merkez(a) + n * (self.yari(yuz) + 1.0) + GO.EKSEN[dik] * kayma
        cut = GO.silindir(p, -n, cap / 2.0, self.t + 1.6)
        self.kesikler.append(dict(sh=cut, tip=tip, yuz=yuz, a=round(a - self.a0, 2), kayma=kayma, cap=cap, not_=not_)); self._sh = None
        return cut

    def duvar_pencere(self, yuz, a, kayma, la, lk, r=1.0, tip="pencere", not_=""):
        sg = 1.0 if yuz[0] == "+" else -1.0
        dik = [k for k in "xyz" if k not in (self.eksen, yuz[1])][0]
        c = self.merkez(a); h = self.yari(yuz)
        lo, hi = np.zeros(3), np.zeros(3)
        for i, k in enumerate("xyz"):
            if k == self.eksen: lo[i], hi[i] = a - la / 2.0, a + la / 2.0
            elif k == dik: lo[i], hi[i] = c[i] + kayma - lk / 2.0, c[i] + kayma + lk / 2.0
            else:
                d0, d1 = c[i] + sg * (h - self.t - 0.6), c[i] + sg * (h + 1.0)
                lo[i], hi[i] = min(d0, d1), max(d0, d1)
        cut = kutu(lo[0], hi[0], lo[1], hi[1], lo[2], hi[2])
        self.kesikler.append(dict(sh=cut, tip=tip, yuz=yuz, a=round(a - self.a0, 2), kayma=kayma, olcu=[la, lk], not_=not_)); self._sh = None
        return cut

    def dfm(self):
        out = []
        L = self.a1 - self.a0
        for k in self.kesikler:
            dik = [q for q in "xyz" if q not in (self.eksen, k["yuz"][1])][0]
            duz = self.bo[dik] / 2.0 - self.Ro
            yar = (k.get("cap") or k["olcu"][1]) / 2.0
            ok = abs(k["kayma"]) + yar <= duz + 1e-6
            out.append(dict(kural="profil_duz_yuz", durum="GEÇTİ" if ok else "HATA", detay="%s %s %s Ø/en %.1f kayma %.1f · düz yüz ±%.1f" % (self.ad, k["tip"], k["yuz"], 2 * yar, k["kayma"], duz)))
            la = (k.get("cap") or k["olcu"][0]) / 2.0
            uc = min(k["a"] - la, L - k["a"] - la)
            out.append(dict(kural="profil_uc", durum="GEÇTİ" if uc >= 3.0 else "HATA", detay="%s %s → boru ucu %.1f (≥ 3)" % (self.ad, k["tip"], uc)))
            for (yz, b0, b1) in self.uc_kaynak:
                if yz == k["yuz"] and b0 - la - 3.0 < k["a"] < b1 + la + 3.0:
                    out.append(dict(kural="profil_kaynak_bolgesi", durum="HATA", detay="%s %s kaynaklı birleşim bölgesinde (%s %.0f–%.0f)" % (self.ad, k["tip"], yz, b0, b1)))
        out.append(dict(kural="profil_boy", durum="GEÇTİ" if L <= 6000 else "HATA", detay="%s L %.1f ≤ 6000 (boy stoğu)" % (self.ad, L)))
        return out

    def parca(self):
        p = super().parca()
        dik = [k for k in "xyz" if k != self.eksen]
        a, b = self.bo[dik[0]], self.bo[dik[1]]
        L = self.a1 - self.a0
        p["bom"] = ("Dikdörtgen boru AISI 304 %g × %g × %g (EN 10217-7 / ASTM A554 · dış R %g) · %s" % (max(a, b), min(a, b), self.t, self.Ro, self.not_), 1, "L %.1f" % L,
                    p["bom"][3], "ÜRETİM")
        p["meta"]["kesit"] = [max(a, b), min(a, b), self.t, self.Ro]
        return p


