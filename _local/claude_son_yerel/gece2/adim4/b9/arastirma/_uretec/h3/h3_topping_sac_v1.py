def bas_ac_d(g, K, dikme, kenar, konumlar, a=22.0, olcu=None):
    """GO.bas_ac'ın dikdörtgen boru sürümü (yanal yarı ölçü ve derinlik ayrı) — gövde dikmenin içinde, baş ön yüzde, uç kapak iç düzlemine"""
    m = dict(GO.BASAC, **(olcu or {}))
    av, bv = K.eksenler(kenar); nv = K.n
    yuz_on = GO._yuz_adi(nv)
    ki = K.ki
    hu, hv = m["karsilik"]
    adlar = []
    i0 = len(K.basaclar)
    for j, s in enumerate(konumlar):
        i = i0 + j; ad = "%s_basac_%d" % (K.ad, i)
        L = GO._hinge_L(K, kenar, s)
        C, a_c, w_c = GO._dikme_yeri(K, dikme, kenar, L, a)
        lat = dikme.bo["xyz"[int(np.argmax(np.abs(av)))]] / 2.0
        dep = dikme.bo[yuz_on[1]] / 2.0
        w_on = w_c + dep
        rg = m["govde_cap"] / 2.0
        if not (a_c - lat + dikme.t <= a - rg and a + rg <= a_c + lat - dikme.t): raise ValueError("%s: bas-aç gövdesi dikme %s boşluğuna sığmıyor" % (ad, dikme.ad))
        if w_on - m["govde_boy"] < w_c - dep + dikme.t - 1e-6: raise ValueError("%s: bas-aç gövdesi dikmenin arka duvarına değer" % ad)
        uc_len = K.w_ic - w_on - m["bas_h"]
        if uc_len <= 1e-6: raise ValueError("%s: dikme ön yüzü kapak iç düzlemine çok yakın" % ad)
        dikme.duvar_delik_nokta(yuz_on, L(a, 0.0, w_on), m["delik_cap"], tip="basac_deligi", not_="bas-aç gövdesi (geçme)")
        sh = GO.silindir(L(a, 0.0, w_on - m["govde_boy"]), nv, rg, m["govde_boy"]).fuse(GO.silindir(L(a, 0.0, w_on), nv, m["bas_cap"] / 2.0, m["bas_h"])) \
            .fuse(GO.silindir(L(a, 0.0, w_on + m["bas_h"]), nv, m["uc_cap"] / 2.0, uc_len))
        g.eleman(g.ozel(ad, sh, m["sinif"], "Bas-aç mandalı (push-to-open, geçme gövde Ø%g × %g · O-ring) — dikme ön yüzünde Ø%g" % (m["govde_cap"], m["govde_boy"], m["delik_cap"]),
                        "Ø%g × %g · baş Ø%g × %g · strok %g" % (m["govde_cap"], m["govde_boy"], m["bas_cap"], m["bas_h"], m["strok"]), malzeme=m["malzeme"], mal="siyah"), sabit=K)
        dp = g.sac("%s_karsilik_%d" % (K.ad, i), m["karsilik_rol"], mal=K.mal, doner=K)
        uc_, vc_ = K.uv(kenar, s, a, 0.0)
        su, sv = (hu, hv) if abs(abs(np.dot(av, K.ex)) - 1.0) < 1e-9 else (hv, hu)
        dp.taban([(uc_ - su, vc_ - sv), (uc_ + su, vc_ - sv), (uc_ + su, vc_ + sv), (uc_ - su, vc_ + sv)], O=tuple(K.kf(0.0, 0.0, K.w_ic + ki.t)),
                 ex=tuple(K.ex), ey=tuple(K.ey), ad="plaka")
        dp.punta(ki, [tuple(L(a + pa * 0.7, pb * 0.7, K.w_ic + ki.t)) for pa, pb in m["punta"]], not_="karşılık takviyesi → iç tava (kapak kapanmadan önce)")
        K.basaclar.append(dict(ad=ad, kenar=kenar, konum=s, a=a, dikme=dikme.ad))
        adlar.append(ad)
    return adlar


